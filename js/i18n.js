let currentLang = 'en';

const PREP_IMAGES = {
  en: 'Assests/preparation/easy-en.webp',
  ar: 'Assests/preparation/easy-ar.webp',
};

function updatePreparationImage(lang = currentLang) {
  const img = document.getElementById('prepImg');
  if (img) {
    const src = PREP_IMAGES[lang === 'ar' ? 'ar' : 'en'];
    if (img.getAttribute('src') !== src) img.src = src;
  }
  const frame = document.getElementById('prepVideo');
  if (frame) frame.setAttribute('title', t('prep.videoTitle'));
}

const THIAFA_ORIGIN = 'https://thiafa.com';

function thiafaLocale(lang = currentLang) {
  return lang === 'ar' ? 'ar' : 'en';
}

function thiafaUrl(path, lang = currentLang) {
  const normalized = path.startsWith('/') ? path : `/${path}`;
  return `${THIAFA_ORIGIN}/${thiafaLocale(lang)}${normalized}`;
}

function applyThiafaLinks(lang = currentLang) {
  document.querySelectorAll('[data-thiafa-path]').forEach((el) => {
    const path = el.getAttribute('data-thiafa-path');
    if (path) el.href = thiafaUrl(path, lang);
  });
}

function t(key) {
  return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
}

const LANG_BTN_LABELS = { en: 'EN', ar: 'عربي' };

function updateLangButtons() {
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    const code = btn.dataset.lang;
    if (code && LANG_BTN_LABELS[code]) {
      btn.textContent = LANG_BTN_LABELS[code];
    }
    const on = code === currentLang;
    btn.classList.toggle('is-active', on);
    btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  });
}

function applyI18nElements() {
  const group = document.querySelector('.lang-switch[aria-label]');
  if (group) group.setAttribute('aria-label', t('lang.label'));

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (el.classList.contains('lang-btn')) return;
    const key = el.dataset.i18n;
    const val = t(key);
    if (!val) return;
    if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = val;
    } else {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.setAttribute('alt', t(el.dataset.i18nAlt));
  });
}

