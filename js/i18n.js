  getLang() {
    const stored = localStorage.getItem(this.storageKey);
    if (stored === "en" || stored === "ar") return stored;
    const browser = (navigator.language || "en").toLowerCase();
    return browser.startsWith("ar") ? "ar" : "en";
  },

  t(key, lang) {
    const l = lang || this.getLang();
    return this.translations[l][key] || this.translations.en[key] || key;
  },

  apply(lang) {
    const l = lang || this.getLang();
    localStorage.setItem(this.storageKey, l);

    document.documentElement.lang = l;
    document.documentElement.dir = l === "ar" ? "rtl" : "ltr";

    const pageKey = document.body.dataset.page;
    if (pageKey) {
      document.title = this.t(`meta.title.${pageKey}`, l);
    }

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const value = this.t(key, l);
      if (el.hasAttribute("data-i18n-html")) return;
      if (value.includes("\n")) {
        el.innerHTML = value
          .split("\n")
          .map((line) => (line.trim() ? `<p>${line}</p>` : ""))
          .join("");
      } else if (
        el.tagName === "INPUT" &&
        (el.type === "submit" || el.type === "button")
      ) {
        el.value = value;
      } else {
        el.textContent = value;
      }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = this.t(el.getAttribute("data-i18n-html"), l);
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", this.t(el.getAttribute("data-i18n-alt"), l));
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = this.t(el.getAttribute("data-i18n-placeholder"), l);
    });

    document.querySelectorAll(".lang-switcher button").forEach((btn) => {
      const btnLang = btn.dataset.lang;
      btn.classList.toggle("active", btnLang === l);
      btn.setAttribute("aria-pressed", btnLang === l ? "true" : "false");
    });
  },

  init() {
    this.apply(this.getLang());

    document.querySelectorAll(".lang-switcher button").forEach((btn) => {
      btn.addEventListener("click", () => {
        const lang = btn.dataset.lang;
        if (lang === "en" || lang === "ar") {
          this.apply(lang);
        }
      });
    });
  },
